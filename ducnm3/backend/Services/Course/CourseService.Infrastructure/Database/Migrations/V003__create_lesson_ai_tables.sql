CREATE TABLE lesson_attachment_texts (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID định danh bản trích xuất',
    lesson_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID Lesson sở hữu tài liệu',
    media_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID media đính kèm từ Media Service; logical reference',
    file_name VARCHAR(255) NOT NULL COMMENT 'Tên tệp gốc tại lúc đưa vào hàng chờ, để hiển thị',
    content_type VARCHAR(150) CHARACTER SET ascii NOT NULL COMMENT 'MIME type của tệp tại lúc đưa vào hàng chờ',
    status VARCHAR(20) CHARACTER SET ascii NOT NULL COMMENT 'PENDING | EXTRACTING | EXTRACTED | FAILED | UNSUPPORTED',
    extracted_text MEDIUMTEXT NULL COMMENT 'Văn bản (Markdown) đã trích xuất; chỉ có khi EXTRACTED',
    error_code VARCHAR(60) CHARACTER SET ascii NULL COMMENT 'Mã lỗi an toàn khi FAILED hoặc UNSUPPORTED',
    error_message VARCHAR(500) NULL COMMENT 'Thông báo lỗi an toàn hiển thị cho admin',
    attempts INT NOT NULL DEFAULT 0 COMMENT 'Số lần worker đã nhận trích xuất tài liệu này',
    locked_until DATETIME(6) NULL COMMENT 'Hạn lease của worker đang trích xuất, UTC; quá hạn thì worker khác nhận lại',
    requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID admin đã yêu cầu; dùng làm actor khi gọi AI Service',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT 'Thời điểm vào hàng chờ, UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT 'Thời điểm cập nhật gần nhất, UTC',
    CONSTRAINT pk_lesson_attachment_texts PRIMARY KEY (id),
    CONSTRAINT fk_lesson_attachment_texts_lesson_id FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT uq_lesson_attachment_texts_lesson_id_media_id UNIQUE (lesson_id, media_id),
    CONSTRAINT chk_lesson_attachment_texts_status CHECK (status IN ('PENDING', 'EXTRACTING', 'EXTRACTED', 'FAILED', 'UNSUPPORTED')),
    INDEX ix_lesson_attachment_texts_status_created_at (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE lesson_ai_jobs (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID định danh job AI',
    lesson_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID Lesson mà job ghi kết quả vào',
    course_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID Course của Lesson, dùng khi gọi handler cập nhật Lesson',
    job_type VARCHAR(30) CHARACTER SET ascii NOT NULL COMMENT 'SYNTHESIZE_LESSON | GENERATE_QUIZ',
    status VARCHAR(20) CHARACTER SET ascii NOT NULL COMMENT 'PENDING | RUNNING | COMPLETED | FAILED',
    media_ids_json JSON NOT NULL COMMENT 'Mảng UUID media (tài liệu) mà admin đã chọn làm nguồn',
    question_count INT NULL COMMENT 'Số câu hỏi yêu cầu khi GENERATE_QUIZ; NULL với SYNTHESIZE_LESSON',
    overwrite_content TINYINT(1) NOT NULL DEFAULT 0 COMMENT 'Admin đã xác nhận cho ghi đè nội dung Lesson đang có',
    previous_content_markdown MEDIUMTEXT NULL COMMENT 'Nội dung Lesson trước khi job ghi đè, để khôi phục',
    result_quiz_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'UUID Quiz DRAFT do job tạo; chỉ có khi GENERATE_QUIZ hoàn tất',
    step_count INT NOT NULL DEFAULT 0 COMMENT 'Số lượt gọi model của job',
    error_code VARCHAR(60) CHARACTER SET ascii NULL COMMENT 'Mã lỗi an toàn khi FAILED',
    error_message VARCHAR(500) NULL COMMENT 'Thông báo lỗi an toàn hiển thị cho admin',
    locked_until DATETIME(6) NULL COMMENT 'Hạn lease của worker đang chạy job, UTC; quá hạn thì worker khác nhận lại',
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'UUID admin tạo job; dùng làm actor khi gọi AI Service và ghi dữ liệu',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT 'Thời điểm tạo job, UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT 'Thời điểm cập nhật gần nhất, UTC',
    started_at DATETIME(6) NULL COMMENT 'Thời điểm worker bắt đầu chạy, UTC',
    finished_at DATETIME(6) NULL COMMENT 'Thời điểm job kết thúc (COMPLETED hoặc FAILED), UTC',
    CONSTRAINT pk_lesson_ai_jobs PRIMARY KEY (id),
    CONSTRAINT fk_lesson_ai_jobs_lesson_id FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT chk_lesson_ai_jobs_job_type CHECK (job_type IN ('SYNTHESIZE_LESSON', 'GENERATE_QUIZ')),
    CONSTRAINT chk_lesson_ai_jobs_status CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    INDEX ix_lesson_ai_jobs_lesson_id_created_at (lesson_id, created_at DESC),
    INDEX ix_lesson_ai_jobs_status_created_at (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
